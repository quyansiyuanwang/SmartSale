export function buildSeedSales(products: Product[], now = Date.now()): SaleRecord[] {
  return SALES_PLAN.map(([name, qty, hoursAgo], i) => {
    const p = products.find((x) => x.name === name) ?? products[0];
    return {
      id: `s${i + 1}`,
      productId: p.id,
      productName: p.name,
      qty,
      unitPrice: p.price,
      cost: p.buyPrice,
      total: Math.round(p.price * qty * 100) / 100,
      time: new Date(now - hoursAgo * 3600 * 1000).toISOString()
    };
  });
}

